/**
 * Pure systemd unit rendering shared by the installer (`systemd-unit.mjs`) and
 * the runtime ownership proof (`lib/managed-apps`). Keeping the exact bytes in
 * one place means the producer and consumer cannot drift into a fake fixture.
 *
 * Validation belongs to the caller: `systemd-unit.mjs` rejects non-absolute,
 * dynamic, loopback, or malformed configuration before calling this.
 */

const CONTROL = /[\0\r\n]/

/** @param {string} value */
export function systemdQuote(value) {
  if (typeof value !== 'string' || value.length === 0 || CONTROL.test(value)) {
    throw new Error('unit value must be a non-empty string without control characters')
  }
  const escaped = value
    .replace(/%/g, '%%')
    .replace(/\$/g, () => '$$')
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
  return `"${escaped}"`
}

/**
 * @typedef {object} UnitRenderInput
 * @property {string} marker
 * @property {string} serviceName
 * @property {string} hostNode
 * @property {string} cliScript
 * @property {string} managedRoot
 * @property {number} port
 * @property {string} advertisedEndpoint
 */

/**
 * @param {UnitRenderInput} input
 */
export function renderUnitText({ marker, serviceName, hostNode, cliScript, managedRoot, port, advertisedEndpoint }) {
  const argv = [
    hostNode,
    cliScript,
    'run',
    '--managed-root',
    managedRoot,
    '--port',
    String(port),
    '--advertised-endpoint',
    advertisedEndpoint
  ]

  return `${marker}
# Generated by MSO's managed-app-orca adapter. Do not edit by hand; reinstall
# through MSO instead. This unit runs only the pinned, verified Orca release
# under the MSO-owned managed root. It contains no credential.
[Unit]
Description=Orca web workspace (MSO managed ${serviceName})
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=300
StartLimitBurst=3

[Service]
Type=simple
WorkingDirectory=${systemdQuote(managedRoot)}
ExecStart=${argv.map(systemdQuote).join(' ')}
Environment="NODE_ENV=production"
Restart=on-failure
RestartSec=5
TimeoutStartSec=90
TimeoutStopSec=20
KillMode=process
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=default.target
`
}
